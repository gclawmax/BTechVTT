// Generate only migration 151 from the browser's deterministic map definitions.
const fs=require('fs'),vm=require('vm');const context=vm.createContext({});
vm.runInContext(fs.readFileSync('js/game/maps.js','utf8'),context);
const maps=context.buildReferenceMapFamilies();
let sql=`-- Generated by tools/build-reference-map-sql.cjs. Run after 150.
-- Native terrain inspired by local map references; original PDF artwork is not shipped.
CREATE OR REPLACE FUNCTION public.btech_reference_map(p_map text)
RETURNS jsonb LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
 SELECT $maps$${JSON.stringify(maps)}$maps$::jsonb->p_map
$$;
REVOKE ALL ON FUNCTION public.btech_reference_map(text) FROM PUBLIC;

DO $migration$
DECLARE source text;patched text;signature text;body text;
BEGIN
`;
const patches=[
['btech_terrain(text,text)',"IF btech_reference_map(p_map) IS NOT NULL THEN RETURN coalesce(btech_reference_map(p_map)->'terrain'->>p_code,'clear');END IF;"],
['btech_elevation(text,text)',"IF btech_reference_map(p_map) IS NOT NULL THEN RETURN coalesce((btech_reference_map(p_map)->'elevation'->>p_code)::int,0);END IF;"],
['btech_map_dimensions(text)',"IF btech_reference_map(p_map) IS NOT NULL THEN RETURN jsonb_build_object('columns',(btech_reference_map(p_map)->>'columns')::int,'rows',(btech_reference_map(p_map)->>'rows')::int);END IF;"],
['btech_scenario_zone_contains(jsonb,integer,text)',"IF btech_reference_map(p_state->>'map_id') IS NOT NULL AND NOT (p_state ? 'deployment_zones') THEN RETURN coalesce((btech_reference_map(p_state->>'map_id')->'deployment_zones'->p_seat::text) ? p_code,false);END IF;"]];
for(const [signature,body] of patches)sql+=` SELECT pg_get_functiondef('public.${signature}'::regprocedure) INTO source;
 IF position('reference_maps_v1' IN source)=0 THEN
  patched:=regexp_replace(source,'\\mBEGIN\\M',$patch$BEGIN /* reference_maps_v1 */ ${body}$patch$,'i');
  IF patched=source THEN RAISE EXCEPTION 'Could not patch ${signature}';END IF;
  EXECUTE patched;
 END IF;
`;
const cases=Object.entries(maps).map(([id,map])=>` WHEN '${id}' THEN '${JSON.stringify(map.objective_hexes)}'::jsonb`).join('\n');
sql+=` SELECT pg_get_functiondef('public.btech_scenario_objective_hexes(text)'::regprocedure) INTO source;
 IF position('reference_maps_v1' IN source)=0 THEN
  patched:=replace(source,'CASE p_map_id',$patch$CASE p_map_id /* reference_maps_v1 */\n${cases}$patch$);
  IF patched=source THEN RAISE EXCEPTION 'Could not patch objective hexes';END IF;
  EXECUTE patched;
 END IF;
END $migration$;
`;
fs.writeFileSync('SQL/151_reference_inspired_maps.sql',sql);
console.log('Generated migration 151 for nine maps.');
